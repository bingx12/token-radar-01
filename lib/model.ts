// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the floor that the house's own watchlist rule would keep: no token on
// record, not a bridge, liquid-staking or restaking product, no versioned pool, no wrapped or staked
// name. The live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The multiple is not a house constant:
// it is the category's own comparable, the median market-cap-to-TVL ratio of the live-token
// protocols in that category in this same snapshot, winsorised at the 90th percentile so one
// outlier cannot set the price. A category with fewer than three live comparables falls back to
// the whole market's median. Then:
//
//   base       = tvl_usd x category_multiple          (category multiple, clamped 0.05..1.20)
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.70 + min(age_days, 1095) / 1095 x 0.30   (age_days unknown: 365)
//   breadth    = 1 + 0.04 x min(chains - 1, 5)              (multi-chain presence, max 1.20)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// The constants are the model's, stated in the dashboard and changeable in the model sandbox. No
// protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

